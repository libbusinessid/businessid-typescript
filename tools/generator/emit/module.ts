/* Dispatch                                                                   */
/* -------------------------------------------------------------------------- */

function emitDispatch(bundle: LoadedBundle): string[] {
  const dispatchers = [...bundle.dispatchers.values()];
  const indexOf = new Map<string, number>(
    dispatchers.map((dispatcher, index) => [dispatcher.kind, index]),
  );

  const kindCases: string[] = [];
  for (const [token, dispatcher] of [...bundle.kindIndex.entries()].sort()) {
    kindCases.push(
      `    case ${quote(token)}:\n      return ${String(indexOf.get(dispatcher.kind) ?? -1)};`,
    );
  }

  const lines: string[] = [
    "/**",
    " * The dispatcher a normalized kind token selects, or -1.",
    " *",
    " * Canonical kinds and their aliases share one space, which the loader proved",
    " * holds no collision, so a single switch decides it.",
    " */",
    "export function dispatcherOf(kind: string): number {",
    "  switch (kind) {",
    ...kindCases,
    "    default:",
    "      return -1;",
    "  }",
    "}",
    "",
    "/** The canonical kind of a dispatcher. */",
    "export function canonicalKindOf(dispatcher: number): string {",
    "  switch (dispatcher) {",
    ...dispatchers.map(
      (dispatcher, index) => `    case ${String(index)}:\n      return ${quote(dispatcher.kind)};`,
    ),
    "    default:",
    `      return "";`,
    "  }",
    "}",
    "",
    "/** Runs the pre-canonicalization program of a dispatcher, exactly once. */",
    "export function preCanonicalize(dispatcher: number, value: readonly number[]): readonly number[] {",
    "  switch (dispatcher) {",
    ...dispatchers.map((dispatcher, index) => {
      const program = bundle.programs.get(dispatcher.preCanonicalizationProgram);
      if (program === undefined) {
        throw new GeneratorError(`dispatcher ${dispatcher.kind} has no pre-canonicalizer`);
      }
      return `    case ${String(index)}:\n      return ${nameOf(program)}(value);`;
    }),
    "    default:",
    "      return value;",
    "  }",
    "}",
    "",
    "/** Normalizes a country token through the alias table of a dispatcher. */",
    "export function aliasCountry(dispatcher: number, country: string): string {",
    "  switch (dispatcher) {",
    ...dispatchers.flatMap((dispatcher, index) => {
      if (dispatcher.countryAliases.size === 0) {
        return [];
      }
      return [
        `    case ${String(index)}:`,
        `      switch (country) {`,
        ...[...dispatcher.countryAliases.entries()].map(
          ([alias, canonical]) =>
            `        case ${quote(alias)}:\n          return ${quote(canonical)};`,
        ),
        `        default:`,
        `          return country;`,
        `      }`,
      ];
    }),
    "    default:",
    "      return country;",
    "  }",
    "}",
    "",
    "/** The definition a country selects within a dispatcher, or -1. */",
    "export function definitionForCountry(dispatcher: number, country: string): number {",
    "  switch (dispatcher) {",
    ...dispatchers.flatMap((dispatcher, index) => {
      if (dispatcher.targetsByCountry.size === 0) {
        return [];
      }
      return [
        `    case ${String(index)}:`,
        `      switch (country) {`,
        ...[...dispatcher.targetsByCountry.entries()].map(
          ([country, target]) =>
            `        case ${quote(country)}:\n          return ${String(target.definitionId)};`,
        ),
        `        default:`,
        `          return -1;`,
        `      }`,
      ];
    }),
    "    default:",
    "      return -1;",
    "  }",
    "}",
    "",
    "/**",
    " * The definition the longest accepted prefix of a value selects, or -1.",
    " *",
    " * Prefixes are declared ASCII, so a value whose head is not ASCII matches",
    " * nothing. The loader proved no prefix belongs to two targets, so the longest",
    " * match is the only decision to make.",
    " */",
    "export function definitionForPrefix(dispatcher: number, value: readonly number[]): number {",
    "  switch (dispatcher) {",
    ...dispatchers.flatMap((dispatcher, index) => emitPrefixCase(dispatcher, index)),
    "    default:",
    "      return -1;",
    "  }",
    "}",
    "",
    "/** The GLOBAL target of a dispatcher, or -1. */",
    "export function globalDefinitionOf(dispatcher: number): number {",
    "  switch (dispatcher) {",
    ...dispatchers.flatMap((dispatcher, index) =>
      dispatcher.globalTarget === undefined
        ? []
        : [
            `    case ${String(index)}:\n      return ${String(dispatcher.globalTarget.definitionId)};`,
          ],
    ),
    "    default:",
    "      return -1;",
    "  }",
    "}",
    "",
    "/** The single target selectable with neither country nor prefix, or -1. */",
    "export function implicitDefinitionOf(dispatcher: number): number {",
    "  switch (dispatcher) {",
    ...dispatchers.flatMap((dispatcher, index) =>
      dispatcher.implicitTarget === undefined
        ? []
        : [
            `    case ${String(index)}:\n      return ${String(dispatcher.implicitTarget.definitionId)};`,
          ],
    ),
    "    default:",
    "      return -1;",
    "  }",
    "}",
  ];
  return lines;
}

function emitPrefixCase(dispatcher: IrDispatcher, index: number): string[] {
  if (dispatcher.targetsByPrefix.size === 0) {
    return [];
  }
  const byLength = new Map<number, [string, number][]>();
  for (const [prefix, target] of dispatcher.targetsByPrefix) {
    // Counted in code points, like every length the IR states. A prefix is
    // proven ASCII by the loader, so the two agree, but the abstraction is what
    // keeps that a fact rather than an assumption.
    const length = codePointsOf(prefix).length;
    const bucket = byLength.get(length) ?? [];
    bucket.push([prefix, target.definitionId]);
    byLength.set(length, bucket);
  }
  const lengths = [...byLength.keys()].sort((left, right) => right - left);
  const lines: string[] = [`    case ${String(index)}: {`];
  for (const length of lengths) {
    lines.push(
      `      const head${String(length)} = support.prefixString(value, ${String(length)});`,
      `      switch (head${String(length)}) {`,
      ...(byLength.get(length) ?? []).map(
        ([prefix, definitionId]) =>
          `        case ${quote(prefix)}:\n          return ${String(definitionId)};`,
      ),
      `        default:`,
      `          break;`,
      `      }`,
    );
  }
  lines.push(`      return -1;`, `    }`);
  return lines;
}


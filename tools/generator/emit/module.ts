/**
 * Assembles the generated rules module.
 *
 * What comes out is the whole of the rules as TypeScript: a function per
 * program, a switch per dispatch decision, and read only tables for weights,
 * character sets and remainder maps. The published package carries this file
 * and the primitives it calls, and nothing else — no bundle, no decoder, no
 * interpreter.
 */
import { ChecksumOpKind, ProgramKind } from "../../../generated/entid/ir/v1/rules_pb.js";
import { GeneratorError } from "../errors.js";
import type { IrDefinition, IrDispatcher, IrProgram, LoadedBundle } from "../ir.js";
import { type EmitContext, stringExpression } from "./expression.js";
import { analyseNeeds, type ProgramNeeds } from "./needs.js";
import { chooseBody, programBody } from "./program.js";
import { ConstantPool, HelperPool } from "./pool.js";

import { codePointsOf } from "../../../src/runtime/text.js";

const quote = (value: string): string => JSON.stringify(value);
const indent = (lines: readonly string[]): string[] =>
  lines.map((line) => (line === "" ? line : `  ${line}`));

const HEADER = `// Code generated by tools/generator. DO NOT EDIT.
// Run \`pnpm generate\` after any change to spec/ or to rules.lock.
/* eslint-disable */`;

interface Emitted {
  readonly source: string;
  readonly kinds: readonly string[];
}

/**
 * Where the emitted module finds the primitives it calls.
 *
 * The shipped rules sit beside `src/`, so the default is a plain relative
 * prefix. A test that generates rules into a scratch directory points this at
 * the same modules from wherever it writes them.
 */
export interface EmitOptions {
  readonly importPrefix?: string;
}

function nameOf(program: IrProgram): string {
  const prefix =
    program.kind === ProgramKind.CANONICALIZATION
      ? "canon"
      : program.kind === ProgramKind.FORMAT
        ? "format"
        : "checksum";
  return `${prefix}${String(program.id)}`;
}

/** The parameters a program's function declares, in a fixed order. */
function parameters(program: IrProgram, needs: ProgramNeeds): string[] {
  const out: string[] = [];
  if (program.kind !== ProgramKind.CANONICALIZATION && needs.subject) {
    out.push("subject: StringValue");
  }
  if (program.kind === ProgramKind.CANONICALIZATION || needs.value) {
    out.push("value: readonly number[]");
  }
  if (needs.definition) {
    out.push("definition: number");
  }
  if (needs.profile) {
    out.push("profile: ValidationProfile");
  }
  return out;
}

/** The arguments a call to that program passes, matching `parameters`. */
function callArguments(
  program: IrProgram,
  needs: ProgramNeeds,
  subject: string,
  value: string,
  definition: string,
  profile: string,
): string {
  const out: string[] = [];
  if (program.kind !== ProgramKind.CANONICALIZATION && needs.subject) {
    out.push(subject);
  }
  if (program.kind === ProgramKind.CANONICALIZATION || needs.value) {
    out.push(value);
  }
  if (needs.definition) {
    out.push(definition);
  }
  if (needs.profile) {
    out.push(profile);
  }
  return out.join(", ");
}

const returnTypeOf = (program: IrProgram): string =>
  program.kind === ProgramKind.CANONICALIZATION
    ? "readonly number[]"
    : program.kind === ProgramKind.FORMAT
      ? "AssertionResult"
      : "ChecksumOutcome";

/** Emits the rules module for a bundle that passed every check. */
export function emitModule(bundle: LoadedBundle, options: EmitOptions = {}): Emitted {
  const from = options.importPrefix ?? "./";
  const constants = new ConstantPool();
  const helpers = new HelperPool();
  const needs = analyseNeeds(bundle);

  const needsOf = (programId: number): ProgramNeeds => {
    const found = needs.get(programId);
    if (found === undefined) {
      throw new GeneratorError(`no needs computed for program ${String(programId)}`);
    }
    return found;
  };

  const programs = [...bundle.programs.values()].sort((left, right) => left.id - right.id);
  const programSource = programs
    .flatMap((program) => emitProgram(bundle, program, needsOf, constants, helpers))
    .join("\n");

  // An accessor the rules never call would be an unused declaration, so each
  // one is emitted only when the generated programs reach for it.
  const accessors = [
    ...(programSource.includes("countryPointsOf(") ? emitCountryPoints(bundle, constants) : []),
    ...(programSource.includes("acceptedPrefixesOf(")
      ? emitAcceptedPrefixes(bundle, constants)
      : []),
    ...(programSource.includes("prependedPrefixOf(") ? emitPrependedPrefix(bundle, constants) : []),
  ];

  const kinds = [...bundle.kindIndex.keys()].sort();
  const source = [
    HEADER,
    "",
    `import type { ValidationProfile } from "${from}domain/profile.js";`,
    `import * as support from "${from}runtime/support.js";`,
    `import type { AssertionResult, ChecksumOutcome, StringValue } from "${from}runtime/values.js";`,
    "",
    "/** The business version of the rules this module was generated from. */",
    `export const RULES_VERSION = ${quote(bundle.rulesVersion)};`,
    "",
    "/** The structural version of the IR this module was generated from. */",
    `export const FORMAT_VERSION = ${String(bundle.formatVersion)};`,
    "",
    "/** The capability ids the bundle required, ascending. */",
    `export const CAPABILITIES: readonly number[] = [${[...bundle.capabilities]
      .sort((left, right) => left - right)
      .join(", ")}];`,
    "",
    "/** Every kind token these rules route, canonical kinds and aliases alike. */",
    `export const KINDS: readonly string[] = [${kinds.map(quote).join(", ")}];`,
    "",
    ...constants.declarations(),
    "",
    ...helpers.declarations(),
    "",
    ...accessors,
    "",
    programSource,
    "",
    ...emitDispatch(bundle),
    "",
    ...emitDefinitionMetadata(bundle),
    "",
    ...emitEntries(bundle, needsOf),
    "",
  ].join("\n");

  return { source, kinds };
}

/* -------------------------------------------------------------------------- */
/* Programs                                                                   */
/* -------------------------------------------------------------------------- */

function emitProgram(
  bundle: LoadedBundle,
  program: IrProgram,
  needsOf: (programId: number) => ProgramNeeds,
  constants: ConstantPool,
  helpers: HelperPool,
): string[] {
  const own = needsOf(program.id);
  const isCanonicalization = program.kind === ProgramKind.CANONICALIZATION;
  const local = isCanonicalization ? "current" : "value";

  const context: EmitContext = {
    constants,
    helpers,
    program,
    value: isCanonicalization ? local : "value",
    subject: isCanonicalization ? undefined : "subject",
    definition: "definition",
    profile: "profile",
    nameOf: (programId) => {
      const callee = bundle.programs.get(programId);
      if (callee === undefined) {
        throw new GeneratorError(`call towards unknown program ${String(programId)}`);
      }
      return nameOf(callee);
    },
    argumentsOf: (programId, subject) => {
      const callee = bundle.programs.get(programId);
      if (callee === undefined) {
        throw new GeneratorError(`call towards unknown program ${String(programId)}`);
      }
      return callArguments(callee, needsOf(programId), subject, "value", "definition", "profile");
    },
    chooseOf: (nodeIndex) => `choose${String(program.id)}_${String(nodeIndex)}`,
    chooseArguments: callArguments(program, own, "subject", "value", "definition", "profile"),
  };

  const blocks: string[] = [];

  // Every CHOOSE becomes its own function: its branches are statements, and a
  // WHEN predicate is a condition rather than a value.
  for (const [index, node] of program.nodes.entries()) {
    if (node.operation.family !== "checksum" || node.operation.kind !== ChecksumOpKind.CHOOSE) {
      continue;
    }
    if (index === program.rootNode) {
      continue;
    }
    blocks.push(
      `function ${context.chooseOf(index)}(${parameters(program, own).join(", ")}): ChecksumOutcome {`,
      ...indent(chooseBody(context, index)),
      `}`,
      "",
    );
  }

  blocks.push(
    `function ${nameOf(program)}(${parameters(program, own).join(", ")}): ${returnTypeOf(program)} {`,
    ...indent(programBody(context, program, local)),
    `}`,
    "",
  );
  return blocks;
}


function emitDefinitionMetadata(bundle: LoadedBundle): string[] {
  const definitions = [...bundle.definitions.values()].sort((left, right) => left.id - right.id);
  return [
    "/** The country a definition reports, absent for a GLOBAL definition. */",
    "export function countryOf(definition: number): string | undefined {",
    "  switch (definition) {",
    ...definitions.flatMap((definition) =>
      definition.countryCode === undefined
        ? []
        : [`    case ${String(definition.id)}:\n      return ${quote(definition.countryCode)};`],
    ),
    "    default:",
    "      return undefined;",
    "  }",
    "}",
    "",
    "/**",
    " * The profile a definition applies when the caller states none.",
    " *",
    " * Leaving the profile out is not the same request as passing `compatible`:",
    " * absence is what lets this default apply.",
    " */",
    "export function profileOf(definition: number): ValidationProfile {",
    "  switch (definition) {",
    ...definitions.flatMap((definition) =>
      definition.defaultProfile === "compatible"
        ? []
        : [`    case ${String(definition.id)}:\n      return ${quote(definition.defaultProfile)};`],
    ),
    "    default:",
    `      return "compatible";`,
    "  }",
    "}",
  ];
}

function emitEntries(bundle: LoadedBundle, needsOf: (programId: number) => ProgramNeeds): string[] {
  const definitions = [...bundle.definitions.values()].sort((left, right) => left.id - right.id);

  const entry = (definition: IrDefinition, programId: number, subject: string): string => {
    const program = bundle.programs.get(programId);
    if (program === undefined) {
      throw new GeneratorError(`definition ${String(definition.id)} references a missing program`);
    }
    const args = callArguments(
      program,
      needsOf(programId),
      subject,
      "value",
      String(definition.id),
      "profile",
    );
    return `${nameOf(program)}(${args})`;
  };

  /** The subject a top level invocation starts from. */
  const topSubject = (programId: number): string => {
    const program = bundle.programs.get(programId);
    if (program?.subjectNode === undefined) {
      return "value";
    }
    const context: EmitContext = {
      constants: new ConstantPool(),
      helpers: new HelperPool(),
      program,
      value: "value",
      // A program that computes its own subject cannot read subject() to do it.
      subject: undefined,
      definition: "definition",
      profile: "profile",
      nameOf: () => {
        throw new GeneratorError("a call inside a subject default");
      },
      argumentsOf: () => {
        throw new GeneratorError("a call inside a subject default");
      },
      chooseOf: () => {
        throw new GeneratorError("a choose inside a subject default");
      },
      chooseArguments: "",
    };
    return stringExpression(context, program.subjectNode);
  };

  /*
   * The exported entries keep one shape whatever the rules need, because the
   * pipeline calls them the same way for every definition. A profile no rule
   * reads is named with a leading underscore rather than dropped: changing the
   * arity would make the call site depend on which rules happen to ship.
   */
  const profileName = (bodies: readonly string[]): string =>
    bodies.some((body) => /\bprofile\b/.test(body)) ? "profile" : "_profile";

  const canonicalCases = definitions.map(
    (definition) =>
      `    case ${String(definition.id)}:\n      return ${entry(definition, definition.canonicalizationProgram, "value")};`,
  );
  const formatCases = definitions.map(
    (definition) =>
      `    case ${String(definition.id)}:\n      return ${entry(definition, definition.formatProgram, topSubject(definition.formatProgram))};`,
  );
  const checksumCases = definitions.map((definition) => {
    const reported =
      definition.checksumProgram === undefined
        ? outcomeLiteral(definition.absentChecksumReason)
        : entry(definition, definition.checksumProgram, topSubject(definition.checksumProgram));
    return `    case ${String(definition.id)}:\n      return ${reported};`;
  });

  return [
    "/** Runs the canonicalization program of a definition, exactly once. */",
    "export function canonicalizeWith(",
    "  definition: number,",
    "  value: readonly number[],",
    `  ${profileName(canonicalCases)}: ValidationProfile,`,
    "): readonly number[] {",
    "  switch (definition) {",
    ...canonicalCases,
    "    default:",
    "      return value;",
    "  }",
    "}",
    "",
    "/** Runs the format rule of a definition on its canonical value. */",
    "export function checkFormat(",
    "  definition: number,",
    "  value: readonly number[],",
    `  ${profileName(formatCases)}: ValidationProfile,`,
    "): AssertionResult {",
    "  switch (definition) {",
    ...formatCases,
    "    default:",
    "      return support.PASSED;",
    "  }",
    "}",
    "",
    "/**",
    " * Runs the checksum rule of a definition, or reports why none applies.",
    " *",
    " * A definition either declares a program or declares the reason no algorithm",
    " * is available, never both and never neither, which the loader proved.",
    " */",
    "export function checkChecksum(",
    "  definition: number,",
    "  value: readonly number[],",
    `  ${profileName(checksumCases)}: ValidationProfile,`,
    "): ChecksumOutcome {",
    "  switch (definition) {",
    ...checksumCases,
    "    default:",
    "      return support.UNSUPPORTED_CHECKSUM;",
    "  }",
    "}",
  ];
}

function outcomeLiteral(reasonCode: string | undefined): string {
  if (reasonCode === undefined || reasonCode === "unsupported_checksum") {
    return "support.UNSUPPORTED_CHECKSUM";
  }
  return `{ status: "unsupported", reasonCode: ${quote(reasonCode)} }`;
}

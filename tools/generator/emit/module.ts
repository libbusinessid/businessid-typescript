const pointsOf = (value: string): number[] => codePointsOf(value);

function emitCountryPoints(bundle: LoadedBundle, constants: ConstantPool): string[] {
  const cases = [...bundle.definitions.values()]
    .filter((definition) => definition.countryCode !== undefined)
    .map(
      (definition) =>
        `    case ${String(definition.id)}:\n      return ${constants.codePoints(pointsOf(definition.countryCode ?? ""))};`,
    );
  return [
    "/**",
    " * The country of the target a definition belongs to, as code points.",
    " *",
    " * Absent for a GLOBAL definition, which has no country: `country_code()`",
    " * yields the absent string there, even though the report may still carry the",
    " * normalized country context the caller supplied.",
    " */",
    "function countryPointsOf(definition: number): readonly number[] | undefined {",
    "  switch (definition) {",
    ...cases,
    "    default:",
    "      return undefined;",
    "  }",
    "}",
  ];
}

function emitAcceptedPrefixes(bundle: LoadedBundle, constants: ConstantPool): string[] {
  const cases: string[] = [];
  for (const dispatcher of bundle.dispatchers.values()) {
    for (const target of dispatcher.targets) {
      const names = target.acceptedPrefixes.map((prefix) => constants.codePoints(pointsOf(prefix)));
      cases.push(
        `    case ${String(target.definitionId)}:\n      return ${constants.prefixes(names)};`,
      );
    }
  }
  return [
    "/** The prefixes the target of a definition accepts. */",
    "function acceptedPrefixesOf(definition: number): readonly (readonly number[])[] {",
    "  switch (definition) {",
    ...cases,
    "    default:",
    `      return ${constants.prefixes([])};`,
    "  }",
    "}",
  ];
}

function emitPrependedPrefix(bundle: LoadedBundle, constants: ConstantPool): string[] {
  const cases: string[] = [];
  for (const dispatcher of bundle.dispatchers.values()) {
    for (const target of dispatcher.targets) {
      // The canonical prefix when the target declares one, otherwise its
      // country: the business prefix and the ISO code differ for some targets.
      const prefix = target.canonicalPrefix ?? target.countryCode;
      if (prefix === undefined) {
        continue;
      }
      cases.push(
        `    case ${String(target.definitionId)}:\n      return ${constants.codePoints(pointsOf(prefix))};`,
      );
    }
  }
  return [
    "/**",
    " * The prefix `prepend_country_if_missing` adds for a definition.",
    " *",
    " * The canonical prefix of its target when one is declared, otherwise the",
    " * country code, because a business prefix may differ from the ISO code.",
    " */",
    "function prependedPrefixOf(definition: number): readonly number[] {",
    "  switch (definition) {",
    ...cases,
    "    default:",
    `      return ${constants.codePoints([])};`,
    "  }",
    "}",
  ];
}

